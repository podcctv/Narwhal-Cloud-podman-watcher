const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('../frontend/node_modules/typescript');
const code = ts.transpileModule(fs.readFileSync('frontend/src/components/tcping/model.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const exportsObject = {};
vm.runInNewContext(code, {exports:exportsObject});
const {carrierComparison, connectionSummary, summaryState, compareProvinces} = exportsObject;
const target = (province, carrier, value, success=2, attempts=2, error='') => ({province,carrier,result:value===undefined?null:{median_ms:value,success,attempts,error}});
const nodes = [target('河北','mobile',57.5),target('河北','unicom',70.4),target('河北','telecom',1170.1,1,2,'timeout'),target('广东','telecom',null,0,0,'dns_error'),target('广东','mobile',undefined),target('台湾','custom',15)];
const rows = carrierComparison(nodes), hebei=rows.find(r=>r.province==='河北'), guangdong=rows.find(r=>r.province==='广东');
assert.deepEqual(Array.from(hebei.cells,s=>s.value),[1170.1,70.4,57.5]);
assert.equal(hebei.cells[0].partial,1);assert.equal(summaryState(hebei.cells[0]),'1 目标部分成功');
assert.equal(guangdong.cells[0].value,null);assert.match(summaryState(guangdong.cells[0]),/DNS 失败/);
assert.equal(summaryState(guangdong.cells[1]),'无目标');assert.equal(summaryState(guangdong.cells[2]),'未返回');
assert.equal(rows.length,2);assert.equal(connectionSummary([target('北京','telecom',0)]).value,0);
assert.equal(connectionSummary([target('北京','telecom',20,0,2)]).value,null);
assert.equal(connectionSummary([target('北京','telecom',NaN)]).value,null);
const city = connectionSummary([target('浙江','mobile',20),target('浙江','mobile',40),target('浙江','mobile',null,0,2,'timeout'),target('浙江','mobile',undefined)]);
assert.equal(city.value,30);assert.equal(city.success,4);assert.equal(city.attempts,6);assert.equal(city.pending,1);assert.equal(city.failed,1);
assert.match(summaryState(city),/连接超时/);assert.match(summaryState(city),/1 未返回/);
assert.equal([...rows].sort((a,b)=>compareProvinces(a,b,'latency'))[0].province,'河北');
assert.equal([...rows].sort((a,b)=>compareProvinces(a,b,'issues'))[0].province,'河北');
assert.equal(connectionSummary([]).value,null);
console.log('TCPing carrier aggregation: 22 assertions passed');
